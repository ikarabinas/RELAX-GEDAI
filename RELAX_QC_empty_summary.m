% RELAX_QC_empty_summary() - Template for one file's stage-1 QC summary.
%
% Every summary is built by assigning into this template, so summaries for files that
% were skipped, not cleaned or fully summarised still concatenate into one struct array.

function s = RELAX_QC_empty_summary()
    metrics = struct('blinkRatio', NaN, 'blinkRatioPerChannel', [], 'muscleProportion', NaN, 'muscleStrength', NaN);
    s = struct( ...
        'status', "notCleaned", 'skipReason', "", 'durationSeconds', NaN, 'nChannels', NaN, ...
        'freqs', [], 'psdInput', [], 'psdBaseline', [], 'psdCleaned', [], 'psdRemoved', [], ...
        'inputSrate', NaN, 'varianceRemovedFraction', NaN, ...
        'blinkN', 0, 'blinkTimes', [], 'blinkErpBaseline', [], 'blinkErpCleaned', [], 'blinkErpRemoved', [], ...
        'topoBaseline', [], 'topoCleaned', [], 'topoRemoved', [], 'chanlocs', [], ...
        'metricsBaseline', metrics, 'metricsCleaned', metrics, ...
        'scores', struct('blinkAmplitude', NaN, 'musclePower', NaN, 'popSteps', NaN), ...
        'centres', struct('blink', NaN, 'muscle', NaN), 'muscleChannels', {{}}, 'pop', []);
end
