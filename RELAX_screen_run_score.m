% RELAX_screen_run_score() - Score stage of the residual-noise screen: measure every file,
%                            write residual_screen.mat/.csv and a README.
%
% Usage:
%   >> [screen, meta] = RELAX_screen_run_score(opts);
%
% opts: built by RELAX_residual_screen (.myPath, .outputFolderName, .outDir, .cutoff,
% .sampleSize, .seed, .holeDepthLimit). A cleaned file whose header cannot be read, or lacks
% EEG.allchan or EEG.RELAX.ListOfChannelsAfterRejections, keeps its muscle metrics,
% gets NaN BlinkRatio, NInterpolated and HoleDepth (so it is unscreened), and the error message goes in
% SheetMessage. A cleaned file whose BlinkRatio is NaN for another reason has that reason in
% SheetMessage. See RELAX_screen_score_table for the columns of screen and meta.

function [screen, meta] = RELAX_screen_run_score(opts)

    processed = fullfile(opts.myPath, opts.outputFolderName);
    [T, cfgs] = RELAX_QC_load_tables(fullfile(processed, 'PerParticipantStats'), fullfile(processed, 'Cleaned_Data'));
    cleanedDir = fullfile(processed, 'Cleaned_Data');

    nFiles = height(T);
    metrics = repmat(nanMetrics(), nFiles, 1);
    headerMessages = strings(nFiles, 1);
    for f = find(T.Outcome == "cleaned")'
        cleanedPath = fullfile(cleanedDir, T.File(f) + RELAX_QC_cleaned_suffix(cleanedDir, T.File(f)));
        [metrics(f), headerMessages(f)] = measureOneFile(cleanedPath, T(f, :), cfgs(char(T.Participant(f))), opts);
        fprintf('RELAX_screen_run_score %d/%d %s %s\n', f, nFiles, T.File(f), headerMessages(f));
    end

    [screen, meta] = RELAX_screen_score_table(T, metrics, opts);
    screen.SheetMessage = headerMessages;

    if ~isfolder(opts.outDir), mkdir(opts.outDir); end
    save(fullfile(opts.outDir, 'residual_screen.mat'), 'screen', 'meta');
    RELAX_screen_write_csv(screen, fullfile(opts.outDir, 'residual_screen.csv'));
    writeReadme(screen, meta, fullfile(opts.outDir, 'README.md'));
    fprintf('RELAX_screen_run_score: %s\n', outcomeCounts(screen));
end

function m = nanMetrics()
    m = struct('MuscleProportion', NaN, 'MuscleStrength', NaN, 'BlinkRatio', NaN, 'NInterpolated', NaN, ...
               'HoleDepth', NaN, 'HoleDeepestElectrode', "", 'HoleElectrodes', "", 'Spacing', NaN, ...
               'NInterpolatedLimit', NaN, 'NChannels', NaN, 'MaxProportionDeleted', NaN);
end

function [m, message] = measureOneFile(cleanedPath, row, cfg, opts)
    [header, message] = loadHeader(cleanedPath);
    if message == ""
        [m, message] = RELAX_screen_file_metrics(row, cfg, header.allchan, ...
                                                 string(header.RELAX.ListOfChannelsAfterRejections), opts.holeDepthLimit);
    else
        m = nanMetrics();
        m.MuscleProportion = row.TableCleanedMuscleProportion;
        m.MuscleStrength = row.TableCleanedMuscleStrength;
        warning('RELAX_screen:headerUnreadable', '%s: %s', row.File, message);
    end
end

function [header, message] = loadHeader(cleanedPath)
    header = [];
    message = "";
    try
        header = pop_loadset('filename', char(cleanedPath), 'loadmode', 'info');
    catch err
        message = string(err.message);
        return
    end
    if ~isfield(header, 'allchan') || isempty(header.allchan)
        message = "header has no EEG.allchan";
    elseif ~isfield(header, 'RELAX') || ~isfield(header.RELAX, 'ListOfChannelsAfterRejections')
        message = "header has no EEG.RELAX.ListOfChannelsAfterRejections";
    end
end

function writeReadme(screen, meta, readmePath)
    lines = [ ...
        "# Residual-noise screen", ...
        "", ...
        sprintf("Run on %s with cutoff %g, seed %d.", string(meta.created, 'yyyy-MM-dd'), meta.cutoff, meta.seed), ...
        sprintf("%d cleaned files were scored; the median and scale of each metric come from those files only.", meta.nCleaned), ...
        "", ...
        "## Outcomes", ...
        "", ...
        "- " + outcomeCounts(screen), ...
        "", ...
        "A metric flags a file when its robust z exceeds the cutoff; the <metric>_flag columns hold those flags. " + ...
        "A file is unscreened when a metric other than the muscle slope is missing and no metric flags it.", ...
        "", ...
        "The <metric>_scale columns are the robust SD that z divides by: 1.4826 * MAD, or 1.2533 * mean|x - median| when MAD is 0.", ...
        ""];
    for metric = meta.zeroScaleMetrics
        lines(end + 1) = sprintf("%s has no spread across the cleaned files, so it cannot flag any file in this run.", metric); %#ok<AGROW>
    end
    lines = [lines, "", ...
        "## Reading a sheet", ...
        "", ...
        "Each sheet is named after its file and saved in review/ as a .png and a .pdf. From top to bottom:", ...
        "", ...
        "- The header gives the file's outcome and the reason for it, with a separate line for each metric that flags the file. " + ...
        "A line beginning 'No before-wICA trace:' means the grey before-wICA traces are absent from the sheet, and says why.", ...
        "- The metrics table gives each metric's value, the dataset median, the robust z, the cutoff and the flag. The strip beside each row shows the z of every cleaned file, " + ...
        "with this file as the large dot and the cutoff as the dashed line. A '>' on the right edge is a file beyond the plotted range, counted beside it.", ...
        "- Three muscle windows and three blink windows of 3 s each, loudest first. Cleaned data is blue. " + ...
        "The data before wICA is grey, and appears only when the baseline aligns with the cleaned data. " + ...
        "Each window shows up to 4 blink electrodes and the 2 other channels with the most 20-80 Hz power in that window.", ...
        "- Each window's caption gives its start time and how loud it is: muscle windows give the 20-80 Hz power as a multiple of the file's median, " + ...
        "blink windows give the microvolts left at the blink peak, as a mean over all of the file's blink electrodes (interpolated ones left out), not only the ones drawn. " + ...
        "The scale bar in each window shows its microvolt scale, which differs from window to window. Interpolated channels are marked '(interp.)' on the axis.", ...
        "- The blink-locked maps average every blink in the file (baseline -500 to -300 ms, 50 ms either side of the peak): before wICA, cleaned, and what was removed, " + ...
        "on one colour scale, with the blink-electrode time course beside them. Open rings mark electrodes that were interpolated.", ...
        "", ...
        "Re-scoring with a different cutoff does not remove the sheets already in review/. Clear that folder before running the sheets stage again, " + ...
        "or the old sheets will still show the previous outcomes.", ...
        "", ...
        "A file is acceptable when the windows show no muscle bursts or blink deflections that stand out from the surrounding EEG."];
    writelines(lines, readmePath);
end

function text = outcomeCounts(screen)
    outcomes = ["pass", "fail", "unscreened", "notCleaned"];
    counts = arrayfun(@(o) sum(screen.ScreenOutcome == o), outcomes);
    text = strjoin(outcomes + " " + counts, ", ");
end
